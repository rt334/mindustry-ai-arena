#!/usr/bin/env python3
"""给 API.md 补「并发与执行顺序」。

借鉴自 meow-ai-arena：它是回合制，把结算序写死成六步链，连反偏袒都明写
（「多个有资格玩家在同格同时请求放弹时，所有请求失败，避免按 ID 偏袒」）。

我们是实时游戏 + HTTP 并发，物理上没法给「同时」定一个全局序。但**入队顺序**
是确定的，只是文档里从没写过 —— AI 无从知道两条冲突指令谁先生效。
"""
import pathlib
import sys

P = pathlib.Path(r"C:\dsh\ai-arena\docs\API.md")

ANCHOR = """`admin=true` 的 agent 可以带 `view=all` 参数看全图；非 admin 只能看自己队伍视野。

---

## 三、能获取的信息"""

NEW = """`admin=true` 的 agent 可以带 `view=all` 参数看全图；非 admin 只能看自己队伍视野。

### 并发与执行顺序

**两条指令同时改同一格，谁生效？**

请求**不会立即作用于世界**。所有需要触及世界的端点都经 `Core.app.post` 投递到
**游戏主线程的队列**，由主线程按**入队顺序**逐个执行。

| 情况 | 结果 |
|---|---|
| 同一 tick 内**串行**发两条冲突指令 | 按你发送的顺序执行，后一条看到前一条的结果 |
| 用多线程/异步**并发**发两条冲突指令 | **入队顺序不确定**，谁先谁后都可能 |
| 两条指令间隔一个以上 tick | 按时间先后，无歧义 |

**冲突的典型表现**：两次 `/place` 抢同一格 —— 后执行的那次拿到 `1008`，
响应里的 `conflictAt` 指向被占的那一格。

**要确定性就串行发。** HTTP 往返天然是一个串行点：等上一条响应回来再发下一条，
顺序就完全确定，代价只是多一个往返。并发省下的那点时间，换的是不可复现的竞态。

**主线程超时**：单个请求在主线程队列里等超过 **3000 ms** 会返回 `504` + `code 1007`
（`op_expired`）。大战场导致主线程卡顿时，请求宁可超时也不无限排队 ——
这是为了保护整个接口不被打满（线程池 16 个，见「限流」一节）。

---

## 三、能获取的信息"""


def main():
    text = P.read_text(encoding="utf-8")
    n = text.count(ANCHOR)
    if n != 1:
        print(f"!! 锚点 {n} 次命中（应为 1），未写盘")
        return 1
    P.write_text(text.replace(ANCHOR, NEW), encoding="utf-8")
    print("API.md：已补「并发与执行顺序」")
    return 0


if __name__ == "__main__":
    sys.exit(main())
